// FACE DETECTION, DEMOTED TO CLOSE-RANGE CONFIRMATION.
//
// It used to be the whole perception story and it could not carry it. msr_s8_v1 takes a 160x120
// input with a 16 px smallest anchor, so the smallest face it resolves is ~128 px of the camera's
// 1280x720 -- about 1.1 m. No threshold reaches further; that is the model's input resolution
// against the lens. So motion saliency is primary (motion.h) and this is the confirmation that
// turns "something is moving over there" into "a person is at the robot, facing it".
//
// When it fires it OUTRANKS motion, because it is the only thing in the system that can say a
// person is pointed AT the robot -- the trigger for mutual gaze. See attention.h for how a hit is
// graded; this file does no filtering of its own beyond what the model does internally. The
// detector's own score threshold is a `const` member with no setter and the vendor component is
// NOT forked to change it.
//
// NO LVGL. The old face_probe.cpp drew its own preview canvas and reticle from the detector task,
// which meant a best-effort perception task holding the one LVGL lock. Everything visual now
// belongs to the face app; this file hands back numbers.
//
// Compiled out entirely unless OPENDUBS_FACEDET is set (percept_config.h, generated by build.sh).
// With it unset, esp-dl is never referenced and the linker drops it -- measured byte-identical
// previously, and re-measurable with ./build.sh image.
#pragma once
#include <stdint.h>

// Loads the model. Expensive (several MB of PSRAM, hundreds of ms); call once, off the UI task.
// Returns false when the detector is not compiled in or the model would not load.
bool facedetBegin();

bool facedetAvailable();

// One inference over an RGB888 frame. On a hit, writes the LARGEST box's centre normalised to
// -1..1 in the same convention as motion.cpp, plus the detector's raw score.
//
// Blocks for 25-35 ms (measured, on the reference image). That is why the caller is priority 2
// pinned to CPU1 and why this is gated rather than run per frame.
bool facedetRun(const uint8_t* rgb888, int w, int h, float* nx, float* ny, float* score);

// The compiled-in reference image, run once at startup: it proves the MODEL independently of the
// camera, needs no human and no scene, and gives a latency figure that is comparable across builds
// because the input is byte-identical every time. Writes its verdict into facedetStatus().
void facedetSelfTest();

// Short panel string. Always NUL-terminated. Never nullptr.
const char* facedetStatus();
