#!/usr/bin/env bash
# Build the Tab5 face for the device, the desktop, or both.
#
# This exists because the two drifted: the desktop binary went 45 minutes and several features
# stale while the device kept being flashed, so the simulator was showing old code and could not
# have validated anything. If both are built from one command they cannot diverge.
#
#   ./build.sh both            device + desktop
#   ./build.sh device          idf.py build and flash
#   ./build.sh image           idf.py build ONLY -- no board needed; prints the image size
#   ./build.sh desktop         SDL build and run
#   ./build.sh desktop-build   build the twin only, do NOT run it -- for SSH, CI, and for asking
#                              the question "does it still compile" without opening a window
#   ./build.sh asan            desktop with AddressSanitizer + UndefinedBehaviorSanitizer
#   ./build.sh cost            desktop for ~95 s, then print the dirty-area verdict
#   ./build.sh percept         compile and run the perception self-test ON THE HOST -- no IDF,
#                              no demo tree, no board. Seconds, and it is the only verification
#                              available to someone who does not have the hardware.
#   ./build.sh voice           the same for the voice layer (capture levels, the noise floor,
#                              direction, push-to-talk, the hangover, the half-duplex mute).
#   ./build.sh loopback        Phase B end to end on the host: the head's real framing against
#                              tools/fake_thor.py over a real socket. No board, no IDF.
#
# Point OPENDUBS_DEMO at the M5Tab5-UserDemo clone (see README.md for how to construct it).
# `percept` and `voice` need neither OPENDUBS_DEMO nor an IDF install.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
MODE="${1:-both}"

# The host self-test needs nothing but a C++ compiler, so it must not be gated behind a demo-tree
# path that someone without the hardware will not have set. Handled before DEMO is required.
build_percept() {
    local inc out
    inc="$(mktemp -d)"
    out="$inc/percept_host_test"
    # The flags the device build would generate are deliberately all OFF here. The self-test does
    # not need them: everything it exercises is the same code either way, and on the host the
    # `!defined(ESP_PLATFORM)` branch keeps the instrument present.
    printf '#pragma once\n// generated by build.sh for the HOST self-test: no device flags\n' \
        > "$inc/percept_config.h"
    # -Wall -Wextra -Werror on purpose: this layer is pure compute with no platform excuses, and a
    # warning here is the cheapest bug report available.
    c++ -std=c++17 -O2 -Wall -Wextra -Werror -I "$HERE/app_face" -I "$inc" -o "$out" \
        "$HERE/tools/percept_host_test.cpp" \
        "$HERE/app_face/percept/frame.cpp" \
        "$HERE/app_face/percept/motion.cpp" \
        "$HERE/app_face/percept/attention.cpp" \
        "$HERE/app_face/percept/selfmotion.cpp" \
        "$HERE/app_face/percept/selftest.cpp"
    "$out"
    local rc=$?
    rm -rf "$inc"
    return $rc
}

# Same deal for the voice layer, and for the same reason one step stronger: when this was written
# the demo tree was not on the development machine at all, so this was the ONLY build that ran.
build_voice() {
    local out
    out="$(mktemp -d)/voice_host_test"
    # -Wall -Wextra -Werror on purpose, as with percept: this layer is pure compute with no
    # platform excuses, and a warning here is the cheapest bug report available.
    c++ -std=c++17 -O2 -Wall -Wextra -Werror -I "$HERE/app_face" -o "$out" \
        "$HERE/tools/voice_host_test.cpp" \
        "$HERE/app_face/voice/level.cpp" \
        "$HERE/app_face/voice/listen.cpp" \
        "$HERE/app_face/voice/glance.cpp" \
        "$HERE/app_face/voice/resample.cpp" \
        "$HERE/app_face/voice/upsample.cpp" \
        "$HERE/app_face/voice/selftest.cpp"
    "$out"
}

if [ "$MODE" = "percept" ]; then
    build_percept
    exit $?
fi

if [ "$MODE" = "voice" ]; then
    build_voice
    exit $?
fi

# PHASE B END TO END, against a DIFFERENT PROGRAM. The self-test proves the arithmetic in-process
# and cannot catch a framing mistake, because a bug and its mirror image in the same file agree
# with each other. tools/fake_thor.py is written to the contract in notes/workplan-tab5-audio.md
# rather than to this code, and rejects anything that does not meet it.
build_loopback() {
    local out port rc
    out="$(mktemp -d)/voice_loopback_test"
    c++ -std=c++17 -O2 -Wall -Wextra -Werror -I "$HERE/app_face" -o "$out" \
        "$HERE/tools/voice_loopback_test.cpp" \
        "$HERE/app_face/voice/level.cpp" \
        "$HERE/app_face/voice/resample.cpp" \
        "$HERE/app_face/voice/clip.cpp" \
        "$HERE/app_face/voice/upsample.cpp" \
        "$HERE/app_face/voice/stream.cpp" \
        "$HERE/app_face/voice/wire.cpp"

    # A port per run, so a stale server from an interrupted run cannot make this pass or fail
    # for the wrong reason.
    port=$(( 9400 + (RANDOM % 400) ))
    rc=0
    echo "phase B loopback on 127.0.0.1:$port"

    # mode | extra fake-thor flags
    for spec in "clip|" "nospeech|" "truncate|" "badreply|--garbage" \
                "say|--say-ms 2000" "saystop|--say-ms 2000" "sayshort|--say-ms 400 --no-terminator"; do
        local mode flags log
        mode="${spec%%|*}"
        flags="${spec#*|}"
        log="$(mktemp)"
        # shellcheck disable=SC2086
        python3 "$HERE/tools/fake_thor.py" --port "$port" --once --json $flags > "$log" 2>&1 &
        local srv=$!
        # NO READINESS PROBE HERE. The obvious one -- connect to see if the port is up -- consumes
        # the connection a --once server exists to accept, which made every case fail. The client
        # retries its connect instead.
        if "$out" "$port" "$mode"; then :; else rc=1; fi
        wait "$srv" 2>/dev/null || true
        # The server's own verdict matters as much as the client's: it is the side that rejects a
        # contract violation, and a client that "passed" while the server rejected the message is
        # the exact failure this harness exists to surface.
        if [ "$mode" != "badreply" ] && grep -q '"ok": false' "$log"; then
            echo "  FAIL: the fake Thor REJECTED the $mode message:"
            sed -n 's/.*"reject": "\([^"]*\)".*/        \1/p' "$log"
            rc=1
        fi
        rm -f "$log"
    done
    return $rc
}

if [ "$MODE" = "loopback" ]; then
    build_loopback
    exit $?
fi

DEMO="${OPENDUBS_DEMO:?set OPENDUBS_DEMO to the M5Tab5-UserDemo clone}"
IDF="${OPENDUBS_IDF:-$(dirname "$DEMO")/esp-idf}"

sync_sources() {
    # Sync whole DIRECTORIES, not a hand-maintained file list. The list version copied three of
    # the nine files we own; cues.cpp, cost_gate.* and the startup anim were only ever in the
    # build tree because they had been copied by hand. That is the "I don't know what you
    # flashed" failure waiting to happen: edit cues.cpp, run build.sh, flash the previous image.
    #
    # AND SYNC RECURSIVELY, for the same reason one step further on. app_face/ now has
    # subdirectories (percept/, shared/) because the architecture note's module boundaries are what
    # keep LVGL out of the perception layer -- and a sync that copied only the top level would
    # build yesterday's percept/ against today's app_face.cpp without a word. The vendor's
    # CMakeLists globs `app/*.cpp` with GLOB_RECURSE, so subdirectories need no build change.
    #
    # AND DELETE THE DESTINATION FIRST. A copy that never removes anything leaves a file that was
    # deleted from the repo compiling happily in the demo tree -- which is how a removed
    # app_launcher.cpp produced a confusing link error, and how face_probe.cpp would have gone on
    # being built after being replaced by percept/. Both directories are entirely ours and the
    # generated headers below are written after this, so wiping them costs nothing.
    for d in app_face app_startup_anim; do
        rm -rf "$DEMO/app/apps/$d"
        ( cd "$HERE/$d" && find . -type f \( -name '*.cpp' -o -name '*.h' \) -print0 ) \
        | while IFS= read -r -d '' f; do
            mkdir -p "$DEMO/app/apps/$d/$(dirname "$f")"
            cp "$HERE/$d/$f" "$DEMO/app/apps/$d/$f"
        done
    done
    cp "$HERE/lv_conf.h" "$DEMO/lv_conf.h"
    cp "$HERE/partitions.csv" "$HERE/sdkconfig.defaults" "$DEMO/platforms/tab5/"
    # The dependency manifest is OURS and tracked -- it holds three version pins that were each
    # found the hard way and that used to exist only inside the clone.
    cp "$HERE/idf_component.yml" "$DEMO/platforms/tab5/main/idf_component.yml"

    # DROP THE 934 KB MP3 WE NEVER PLAY. The vendor embeds audio/canon_in_d.mp3 via
    # EMBED_TXTFILES for a music demo: 956,208 bytes, about 25% of our entire 3.94 MB image, and
    # almost exactly what esp-dl costs (~726 KB code + 196 KB model). Nothing in the face plays it.
    # Removing the embed alone breaks the link, because hal_audio.cpp declares the _binary_
    # symbols, so the music test's canon case is pointed at the short startup sfx instead. The two
    # small sfx (42 KB together) stay -- not worth a third vendor edit.
    #
    # Patched here rather than tracked as a whole vendor file copy, so a vendor change to
    # CMakeLists is inherited instead of silently overwritten. Idempotent, and it FAILS LOUDLY if
    # an anchor moves rather than quietly building the 934 KB version again.
    python3 - "$DEMO/platforms/tab5" "$HERE/patches" <<'PATCH'
import pathlib, sys, subprocess
root = pathlib.Path(sys.argv[1])

cm = root / "main/CMakeLists.txt"
t = cm.read_text()
if '"../audio/canon_in_d.mp3" ' in t:
    t = t.replace('"../audio/canon_in_d.mp3" ', '')
    cm.write_text(t)
    print("  patched: canon_in_d.mp3 un-embedded (-934 KB)")
elif 'canon_in_d.mp3' in t:
    sys.exit("REFUSING: canon_in_d.mp3 is embedded in a form this patch does not recognise")

ha = root / "main/hal/components/hal_audio.cpp"
t = ha.read_text()
old = """extern const uint8_t canon_in_d_mp3_start[] asm("_binary_canon_in_d_mp3_start");
extern const uint8_t canon_in_d_mp3_end[] asm("_binary_canon_in_d_mp3_end");"""
if old in t:
    t = t.replace(old, """// canon_in_d.mp3 is no longer embedded -- see build.sh. Aliased to the startup sfx so the
// vendor's music test still links and still makes a noise, without 934 KB of payload.
#define canon_in_d_mp3_start startup_sfx_mp3_start
#define canon_in_d_mp3_end   startup_sfx_mp3_end""")
    ha.write_text(t)
    print("  patched: hal_audio.cpp canon symbols aliased")
elif "canon_in_d_mp3_start[] asm" in t:
    sys.exit("REFUSING: hal_audio.cpp declares the canon symbols in an unrecognised form")

# ---- the vendor's audio task starves perception ---------------------------------------------
# THE PLAYBACK TASK IS CREATED AT PRIORITY 5, UNPINNED, and it is never deleted:
#
#     xTaskCreate(_audio_play_task, "audio", 4096, nullptr, 5, nullptr);
#
# It is created LAZILY, the first time anything calls audioPlay() with async=true -- which is the
# first earcon the robot ever plays -- and then loops `vTaskDelay(10 ms)` for the rest of the boot
# even when nothing is playing. percept, by contrast, runs at priority 2 PINNED TO CPU1 with its
# stack in PSRAM, precisely so that it cannot preempt the animation on CPU0.
#
# So the moment one cue sounds, the head permanently acquires an unpinned priority-5 task waking
# 100 times a second that outranks face detection on EITHER core. Observed on the robot on
# 2026-10-08: detection-driven head turning became "damped -- it takes a fair amount of insistent
# movement", and A RESTART RESTORED IT with the same image and audio still enabled, which is the
# signature of something acquired at runtime rather than built in.
#
# The fix is priority and affinity, not memory: pinned to CPU1 so it can never touch the animation's
# core, and dropped to percept's own priority 2. The stack stays INTERNAL deliberately -- moving it
# to PSRAM would mean i2s_write running on an external stack for no benefit, since the mechanism
# here is scheduling.
#
# Audio quality is not the trade it looks like: i2s_write blocks on DMA with portMAX_DELAY, so the
# buffer drains at its own rate and this task only has to top it up, with tens of milliseconds of
# slack. The other two xTaskCreate calls in this file ("rec" and "music") are left alone: they are
# only ever started by the vendor's own test screens, which the face never opens.
old = 'xTaskCreate(_audio_play_task, "audio", 4096, nullptr, 5, nullptr);'
new = ('xTaskCreatePinnedToCore(_audio_play_task, "audio", 4096, nullptr, 2, nullptr, 1);'
       '  // opendubs: prio 5->2, pinned to CPU1 -- see build.sh')
if old in t:
    t = t.replace(old, new)
    ha.write_text(t)
    print("  patched: hal_audio.cpp playback task pinned to CPU1 at priority 2")
elif new in t:
    print("  ok:      hal_audio.cpp playback task already pinned")
else:
    sys.exit("REFUSING: hal_audio.cpp's audio task is not created in a form this patch recognises "
             "-- the vendor file moved. Re-check its xTaskCreate before building.")

# ---- GT911 self-test + recovery -------------------------------------------------------------
# Touch dies intermittently on this board: the GT911 keeps ACKing I2C while its firmware stops
# reporting, so LVGL sees RELEASED forever and the display is unaffected. Four candidates were
# eliminated by measurement (poll sparsity, wrong I2C address, out-of-range coordinates, the
# board's controller revision) and init order, reset timing and sleep were cleared in source.
# Goodix's own reference driver ships a heartbeat watchdog for exactly this, so what goes in is a
# verify-and-recover that logs its own verdict -- not a fix for a root cause we do not have.
#
# The C lives in firmware/tab5_idf/patches/*.c.inc, NOT in this heredoc: it has to be reviewable,
# greppable and diffable like any other source we own.
bsp = root / "components/m5stack_tab5/m5stack_tab5.c"
# RESTORE THE VENDOR FILE FIRST, THEN ALWAYS RE-PATCH.  Without this the patch is idempotent
# against a file that persists between builds, so EDITING THE .inc WOULD SILENTLY DO NOTHING --
# and the next edit due here is flipping OD_GT911_WATCHDOG, which must actually take effect.
# Only this one file is restored; the CMakeLists and hal_audio patches above stay applied.
import subprocess
r = subprocess.run(["git", "-C", str(root.parent.parent), "checkout", "--",
                    "platforms/tab5/components/m5stack_tab5/m5stack_tab5.c"],
                   capture_output=True, text=True)
if r.returncode != 0:
    sys.exit("REFUSING: could not restore m5stack_tab5.c from git (%s) -- a stale GT911 patch "
             "would silently ignore edits to patches/*.c.inc" % r.stderr.strip())

t = bsp.read_text()
if "od_gt911_selftest" not in t:
    anchor_call = "    esp_lcd_touch_exit_sleep(tp);  // !!!\n"
    anchor_fn   = "static lv_indev_t* bsp_display_indev_init(lv_display_t* disp)\n"
    if anchor_call not in t or anchor_fn not in t:
        sys.exit("REFUSING: GT911 patch anchors not found in m5stack_tab5.c -- the vendor file moved")
    pdir    = pathlib.Path(sys.argv[2])
    helpers = (pdir / "gt911_selftest.c.inc").read_text()
    init    = (pdir / "gt911_init.c.inc").read_text()
    t = t.replace(anchor_fn, helpers + "\n" + anchor_fn, 1)
    t = t.replace(anchor_call, init, 1)

    # Instrument the vendor's LVGL read callback itself. Anchors are matched byte-for-byte and the
    # script refuses if either is not unique, so a vendor change cannot be silently half-applied.
    rb_anchor = "static void lvgl_read_cb(lv_indev_t* indev, lv_indev_data_t* data)\n"
    body_anchor = (
        "    esp_lcd_touch_read_data(_lcd_touch_handle);\n"
        "    bool touchpad_pressed =\n"
        "        esp_lcd_touch_get_coordinates(_lcd_touch_handle, touch_x, touch_y, touch_strength, &touch_cnt, 1);\n"
        "\n"
        "    if (!touchpad_pressed) {\n"
        "        data->state = LV_INDEV_STATE_REL;\n"
        "    } else {\n"
        "        data->state   = LV_INDEV_STATE_PR;\n"
        "        data->point.x = touch_x[0];\n"
        "        data->point.y = touch_y[0];\n"
        "    }\n")
    if t.count(rb_anchor) != 1 or t.count(body_anchor) != 1:
        sys.exit("REFUSING: lvgl_read_cb anchors not unique in m5stack_tab5.c")
    body_new = (
        "    od_tp_polls++;\n"
        "    if (esp_lcd_touch_read_data(_lcd_touch_handle) != ESP_OK) od_tp_errs++;\n"
        "    bool touchpad_pressed =\n"
        "        esp_lcd_touch_get_coordinates(_lcd_touch_handle, touch_x, touch_y, touch_strength, &touch_cnt, 1);\n"
        "\n"
        "    if (!touchpad_pressed) {\n"
        "        data->state = LV_INDEV_STATE_REL;\n"
        "    } else {\n"
        "        data->state   = LV_INDEV_STATE_PR;\n"
        "        data->point.x = touch_x[0];\n"
        "        data->point.y = touch_y[0];\n"
        "        od_tp_lastx = touch_x[0]; od_tp_lasty = touch_y[0];\n"
        "        if ((od_tp_presses++ % 25) == 0)\n"
        "            ESP_LOGI(TAG, \"TP RAW press #%lu at %u,%u cnt=%u (polls %lu errs %lu)\",\n"
        "                     (unsigned long)od_tp_presses, touch_x[0], touch_y[0], touch_cnt,\n"
        "                     (unsigned long)od_tp_polls, (unsigned long)od_tp_errs);\n"
        "    }\n"
        "    { static uint32_t od_last = 0; uint32_t od_now = lv_tick_get();\n"
        "      if (od_now - od_last > 5000) { od_last = od_now;\n"
        "          ESP_LOGI(TAG, \"TP RAW heartbeat: polls %lu presses %lu errs %lu\",\n"
        "                   (unsigned long)od_tp_polls, (unsigned long)od_tp_presses, (unsigned long)od_tp_errs); } }\n")
    t = t.replace(rb_anchor, (pdir / "gt911_rawcount.c.inc").read_text() + "\n" + rb_anchor, 1)
    t = t.replace(body_anchor, body_new, 1)

    bsp.write_text(t)
    print("  patched: GT911 M5GFX bring-up + self-test + raw counters")
else:
    # Unreachable: the file was just restored from git, so it cannot already carry the patch.
    sys.exit("REFUSING: m5stack_tab5.c still carries the GT911 patch after a git restore")
PATCH
    # esp-dl is appended ONLY when the detector is wanted: in the default dependency set it aborts
    # at boot with an i2c driver-generation conflict (see idf_component.yml). Keeping it out of the
    # tracked manifest means a normal build cannot inherit that.
    if [ "$FACEDET" = "1" ]; then
        printf '  espressif/esp-dl: 3.1.3\n  espressif/human_face_detect: 0.2.3\n' \
            >> "$DEMO/platforms/tab5/main/idf_component.yml"
    fi

    # ONE GENERATED HEADER FOR EVERY BUILD FLAG. A generated header rather than a -D because
    # idf.py -D sets a CMake variable, not a compile definition, and bridging it would mean editing
    # the vendor's CMakeLists -- a file we do not own and do not sync. Generated every build and
    # never committed: a checked-in generated file is the thing that drifts.
    #
    # Release is ALL OF THEM OFF, and "off" means the instrument is absent from the image, not
    # merely quiet: each one's translation unit is wrapped in its own #if with no-op fallbacks
    # (the face_probe.cpp pattern, which measured byte-identical).
    {
        echo "#pragma once"
        echo "// GENERATED by build.sh -- do not edit, do not commit."
        [ "$FACEDET" = "1" ]    && echo "#define OPENDUBS_FACEDET 1"
        [ "$DBG_PERCEPT" = "1" ] && echo "#define OPENDUBS_DBG_PERCEPT 1"
        [ "$DBG_SERIAL" = "1" ]  && echo "#define OPENDUBS_DBG_PERCEPT_SERIAL 1"
        [ "${OPENDUBS_WALKIN:-0}" = "1" ] && echo "#define OPENDUBS_WALKIN 1"
        [ "$DBG_UI" = "1" ]      && echo "#define OPENDUBS_DBG_UI 1"
        # VOICE: the microphone capture task. DEFAULT OFF, and not because the code is doubtful --
        # it adds a FreeRTOS task, and a TCB must live in internal DRAM where one more has already
        # asserted in xPortCheckValidTCBMem with esp-dl linked. Off means nobody else's build
        # changes; flip it with OPENDUBS_VOICE=1 when the robot is in front of you.
        [ "${OPENDUBS_VOICE:-0}" = "1" ] && echo "#define OPENDUBS_VOICE 1"
        [ "${OPENDUBS_NO_SCENE:-0}" = "1" ] && echo "#define OPENDUBS_NO_SCENE 1"
        true
    } > "$DEMO/app/apps/app_face/percept/percept_config.h"
    echo "flags: facedet=$FACEDET dbg_percept=$DBG_PERCEPT dbg_serial=$DBG_SERIAL walkin=${OPENDUBS_WALKIN:-0} dbg_ui=$DBG_UI voice=${OPENDUBS_VOICE:-0}"

    # Generate the probe's reference image from the committed .jpg EVERY build. Generated, never
    # committed: a checked-in generated file is the thing that drifts (today's lesson, three times).
    # Wi-Fi credentials, if supplied, as a GENERATED HEADER in the ephemeral build tree.
    # NEVER written into this repo: per-robot secrets do not belong in git, and the generated
    # file lives only in the clone. Needed once per board -- esp_wifi persists to NVS after a
    # successful association, so later builds can omit them entirely.
    if [ -n "${OPENDUBS_WIFI_SSID:-}" ]; then
        printf '#pragma once\n#define OPENDUBS_WIFI_SSID "%s"\n#define OPENDUBS_WIFI_PASS "%s"\n' \
            "$OPENDUBS_WIFI_SSID" "${OPENDUBS_WIFI_PASS:-}" \
            > "$DEMO/app/apps/app_face/net_credentials.h"
        echo "wifi credentials: compiled in for SSID '$OPENDUBS_WIFI_SSID' (one-time provisioning)"
    else
        printf '#pragma once\n// no build-time credentials; NVS-stored ones will be used\n' \
            > "$DEMO/app/apps/app_face/net_credentials.h"
    fi

    # OPENDUBS_NO_MARK_VALID=1 builds the deliberately-bad image for the rollback test: it runs
    # normally but never declares itself good, so the next reboot must revert it.
    if [ "${OPENDUBS_NO_MARK_VALID:-0}" = "1" ]; then
        echo "#pragma once
#define OPENDUBS_NO_MARK_VALID 1" > "$DEMO/app/apps/app_face/rollback_test.h"
        echo "ROLLBACK TEST IMAGE: this build will NOT mark itself valid"
    else
        echo "#pragma once" > "$DEMO/app/apps/app_face/rollback_test.h"
    fi

    # TOUCH UI, same generated-header mechanism and for the same reason: idf.py -D sets a CMake
    # variable, not a compile definition, and bridging it would mean editing the vendor's
    # CMakeLists -- a file we do not own and do not sync.
    #
    # The touch UI is PRODUCT and therefore defaults ON, unlike the probe. OPENDUBS_TOUCH_UI=0
    # takes it out entirely: ui_grade.cpp / ui_controls.cpp / ui_touch.cpp each have an #else
    # branch defining their whole API as no-ops, so app_face.cpp compiles unchanged and the
    # linker drops the lot (the face_probe.cpp pattern, which measured byte-identical).
    #
    # OPENDUBS_TOUCH_DEBUG=1 adds the raw-touch crosshair, which is an INSTRUMENT and defaults
    # off. It is the one thing that settles whether the 90-degree rotation's handedness matches
    # the digitiser, which no amount of reading the source can decide.
    TOUCH_UI="${OPENDUBS_TOUCH_UI:-1}"
    TOUCH_DEBUG="${OPENDUBS_TOUCH_DEBUG:-0}"
    # PAN/TILT DEFAULTS OFF, and that is deliberate for the first robot flash.
    #
    # The module itself is safe on a bench -- it probes 0x25 and self-disables when nothing answers
    # -- but on the ROBOT the 8Servo is present, so without this flag the first IDF flash would
    # make the Tab5's own tracker the sole owner of the head while RC and the Thor's YOLO are not
    # parsed yet. That is a REGRESSION in head control dressed up as a new feature: the operator
    # would lose the stick and gain autonomous motion nobody asked for. Off, the head is inert,
    # which is honest about what this build does and does not do.
    #
    # Turn it on only once the ownership arbitration in notes/design/head-ownership.md exists.
    PANTILT="${OPENDUBS_PANTILT:-0}"
    printf '#pragma once\n// GENERATED by build.sh -- do not edit, do not commit.\n#define OPENDUBS_TOUCH_UI %s\n#define OPENDUBS_TOUCH_DEBUG %s\n#define OPENDUBS_PANTILT %s\n' \
        "$TOUCH_UI" "$TOUCH_DEBUG" "$PANTILT" > "$DEMO/app/apps/app_face/touch_ui_config.h"
    echo "touch UI: $([ "$TOUCH_UI" = 1 ] && echo ON || echo "COMPILED OUT")$([ "$TOUCH_DEBUG" = 1 ] && echo " + crosshair" || true)"
    echo "pan/tilt: $([ "$PANTILT" = 1 ] && echo "ON -- the head will MOVE" || echo "off (head inert)")"

    # The detector's reference image, generated from the committed .jpg EVERY build for the same
    # reason. Only referenced when OPENDUBS_FACEDET is set, but always generated so a flag flip
    # needs no second step.
    python3 - "$HERE/probe/human_face.jpg" > "$DEMO/app/apps/app_face/percept/facedet_image.h" <<'EMBED'
import sys, pathlib
b = pathlib.Path(sys.argv[1]).read_bytes()
print("// GENERATED by build.sh from firmware/tab5_idf/probe/human_face.jpg -- do not edit, do not commit.")
print("#pragma once")
print("#include <stdint.h>")
print(f"// {len(b)} bytes")
print("static const uint8_t kFaceProbeJpeg[] = {")
for i in range(0, len(b), 16):
    print("    " + ",".join(f"0x{c:02x}" for c in b[i:i+16]) + ",")
print("};")
EMBED

    # Then PROVE it synced, RECURSIVELY. A silent cp failure looks exactly like a stale build, and
    # a verification that only walked the top level would miss exactly the files the recursive copy
    # was added for.
    local drift=0 n=0
    for d in app_face app_startup_anim; do
        while IFS= read -r rel; do
            n=$((n + 1))
            cmp -s "$HERE/$d/$rel" "$DEMO/app/apps/$d/$rel" \
                || { echo "NOT SYNCED: $d/$rel"; drift=1; }
        done < <(cd "$HERE/$d" && find . -type f \( -name '*.cpp' -o -name '*.h' \) | sed 's|^\./||')
    done
    [ "$drift" -eq 0 ] || { echo "refusing to build from a tree that does not match the repo"; exit 1; }
    echo "synced and verified $n files into the demo tree"
}

# BUILD FLAGS, all off by default.
#   OPENDUBS_FACEDET=1       compile in esp-dl + the face detector (percept/facedet.cpp). Off, it
#                            costs nothing: esp-dl is never referenced, the linker drops it, model
#                            data included -- previously measured byte-identical.
#   OPENDUBS_DBG_PERCEPT=1   the camera preview canvas, the reticle colours, and the perception
#                            self-test with its verdict on the panel.
#   OPENDUBS_DBG_SERIAL=1    console telemetry from the perception task. OFF BY DEFAULT AND THAT IS
#                            A CORRECTNESS MATTER: a write to USB-serial-JTAG blocks the calling
#                            task when no host is draining the port, so console telemetry is itself
#                            a plausible cause of the freeze it is meant to diagnose. Only turn it
#                            on when someone is actually reading the port.
# OPENDUBS_PROBE_FACEDET is accepted as the old name for OPENDUBS_FACEDET so an existing shell
# alias or note does not silently build the wrong thing.
FACEDET="${OPENDUBS_FACEDET:-${OPENDUBS_PROBE_FACEDET:-0}}"
DBG_PERCEPT="${OPENDUBS_DBG_PERCEPT:-0}"
DBG_SERIAL="${OPENDUBS_DBG_SERIAL:-0}"
