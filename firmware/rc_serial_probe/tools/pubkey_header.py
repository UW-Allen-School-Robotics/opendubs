#!/usr/bin/env python3
"""Write the C header that compiles the firmware-signing PUBLIC key into the StamPLC firmware.

    python3 tools/pubkey_header.py PUBKEY.der > include/ota_pubkey.h

The input is the DER SubjectPublicKeyInfo of the Thor's ECDSA P-256 key
(`openssl pkey -in KEY -pubout -outform DER`). ota-from-thor.sh and flash-from-thor.sh run this
before every build, so the header is generated, never committed. A build without it trusts no key
and refuses every OTA (src/ota_verify.cpp). See notes/design/firmware-signing.md.
"""
import hashlib
import sys

der = open(sys.argv[1], "rb").read()
if not (60 <= len(der) <= 200) or der[0] != 0x30:
    sys.exit(f"{sys.argv[1]}: not a DER public key ({len(der)} bytes)")
rows = [", ".join(f"0x{b:02x}" for b in der[i:i + 12]) for i in range(0, len(der), 12)]
print("// GENERATED by tools/pubkey_header.py from the Thor's firmware-signing public key. Do not")
print("// edit or commit; it is rewritten before every build. Key id " + hashlib.sha256(der).hexdigest()[:16] + ".")
print("#pragma once")
print("#include <stdint.h>")
print("static const uint8_t OTA_PUBKEY_DER[] = {")
print(",\n".join("    " + r for r in rows))
print("};")
