#pragma once
// Signed firmware updates: the check every OpenDubs board runs on an image BEFORE making it
// bootable. Shared by the StamPLC (firmware/rc_serial_probe) and the neck Dial (firmware/neck_dial).
// Design: notes/design/firmware-signing.md. Board integration: README.md beside this file.
//
// What is signed: ECDSA P-256 over SHA-256 of
//
//     "OPENDUBS-FW-SIG-1" \0 <board> \0 <image bytes>
//
// so a signature names the board it is for: a correctly signed StamPLC image fails on the Dial, and
// the other way round. The signature is detached (<image URL>.sig, DER, at most OTA_SIG_MAX bytes),
// made on the Thor by software/stack/firmware-signing/sign-firmware.sh.
//
// The keys a board trusts are compiled in from ota_keys.h (the repository's keys/, generated by
// tools/ota_keys.py): normally one, two during a key rotation. None means every update is refused.
//
// Plain mbedTLS (the md and pk APIs: the same in 2.28 and 3.x) and no Arduino, so the host test runs
// exactly this file.
#include <stddef.h>
#include <stdint.h>
#include "mbedtls/md.h"

#define OTA_SIG_DOMAIN "OPENDUBS-FW-SIG-1"
#define OTA_SIG_MAX 160                 // a DER P-256 signature is at most 72 bytes

enum OtaVerifyResult {
    OTA_SIG_OK = 0,
    OTA_SIG_NO_KEY,         // this build trusts no key
    OTA_SIG_BAD_KEY,        // a compiled-in key does not parse (and no other key matched)
    OTA_SIG_MISSING,        // no signature (empty, or not fetched)
    OTA_SIG_HASH_FAILED,    // SHA-256 could not run
    OTA_SIG_INVALID,        // the signature matches no trusted key for this board and image
};

struct OtaKey { const uint8_t* der; size_t len; };   // DER SubjectPublicKeyInfo

struct OtaVerify {
    mbedtls_md_context_t md;
    bool started;
};

// Start hashing an image for `board` ("stamplc", "neck"): hashes the domain and board name first.
bool otaVerifyBegin(OtaVerify& v, const char* board);
void otaVerifyUpdate(OtaVerify& v, const uint8_t* data, size_t len);
// Finish the hash and accept the signature if ANY of `keys` verifies it. `*which`, when given, is
// the index of the key that did. Frees the context either way.
OtaVerifyResult otaVerifyFinish(OtaVerify& v, const uint8_t* sig, size_t sig_len,
                                const OtaKey* keys, size_t nkeys, int* which = nullptr);
void otaVerifyAbort(OtaVerify& v);
const char* otaVerifyReason(OtaVerifyResult r);

// A key's id: the first 16 hex digits of the SHA-256 of its DER (what the Thor's tools print).
// buf >= 17; "" on failure.
void otaKeyId(const OtaKey& key, char* buf, size_t buflen);

// Known-answer self-test, run at boot: verifies a fixed signature with a fixed test key through
// the same code path. false means THIS BUILD'S VERIFIER IS BROKEN on this board; the board must say
// so, and must not let the broken check strand it (README.md, "Policy").
bool otaVerifySelfTest();
