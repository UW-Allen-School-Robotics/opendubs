#!/usr/bin/env bash
# Regenerate src/ota_selftest.h: the known-answer vector otaVerifySelfTest() checks at boot. A fresh
# throwaway key signs a fixed message exactly as sign-firmware.sh signs an image (domain, board,
# bytes); the private half is deleted at once. Re-running changes the key and signature, not the test.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
BOARD=selftest
MSG="OpenDubs signed-update self-test: a known answer, checked at every boot."
openssl ecparam -name prime256v1 -genkey -noout -out "$W/k" 2>/dev/null
openssl pkey -in "$W/k" -pubout -outform DER -out "$W/pub"
{ printf 'OPENDUBS-FW-SIG-1\0%s\0' "$BOARD"; printf '%s' "$MSG"; } | openssl dgst -sha256 -sign "$W/k" -out "$W/sig"
rm -f "$W/k"
python3 - "$W/pub" "$W/sig" "$BOARD" "$MSG" > "$HERE/src/ota_selftest.h" <<'PY'
import sys
pub, sig = open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read()
def arr(name, b):
    rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return f"static const uint8_t {name}[] = {{\n" + ",\n".join("    " + r for r in rows) + "\n};"
print("// GENERATED by tools/make_selftest.sh: the known-answer vector for otaVerifySelfTest(). The")
print("// key is a throwaway whose private half was deleted when this was made; it signs nothing else.")
print("#pragma once")
print("#include <stdint.h>")
print(f'#define OTA_SELFTEST_BOARD "{sys.argv[3]}"')
print(f'#define OTA_SELFTEST_MSG "{sys.argv[4]}"')
print(arr("OTA_SELFTEST_PUB", pub))
print(arr("OTA_SELFTEST_SIG", sig))
PY
echo "wrote src/ota_selftest.h"
