#!/usr/bin/env python3
"""Generate src/ota_keys.h, the signing keys every OpenDubs firmware trusts, from keys/*.der.

    python3 tools/ota_keys.py           write src/ota_keys.h
    python3 tools/ota_keys.py --check   exit 1 if src/ota_keys.h is stale

keys/ holds the project's firmware-signing PUBLIC keys (DER SubjectPublicKeyInfo), named
<key id>.der, where the id is the first 16 hex digits of the key's SHA-256 (what the Thor's tools
print). Public keys are not secret; committing them means every machine that builds firmware
compiles in the same, reviewed keys. Normally there is one; during a rotation, two. With none,
every firmware refuses every update. See notes/design/firmware-signing.md.
"""
import hashlib
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
OUT = HERE / "src" / "ota_keys.h"


def render():
    keys = []
    for p in sorted((HERE / "keys").glob("*.der")):
        der = p.read_bytes()
        kid = hashlib.sha256(der).hexdigest()[:16]
        if not (60 <= len(der) <= 200) or der[0] != 0x30:
            sys.exit(f"{p}: not a DER public key ({len(der)} bytes)")
        if p.stem != kid:
            sys.exit(f"{p}: named {p.stem} but its key id is {kid}; rename it {kid}.der")
        keys.append((kid, der))
    if len(keys) > 2:
        sys.exit(f"keys/ holds {len(keys)} keys; a board trusts at most two (one, or two in a rotation)")
    out = ["// GENERATED by tools/ota_keys.py from keys/*.der: the firmware-signing keys this build trusts.",
           "// Do not edit; add or remove a key in keys/ and re-run the tool (it has --check).",
           "#pragma once", '#include "ota_verify.h"', ""]
    for i, (kid, der) in enumerate(keys):
        rows = [", ".join(f"0x{b:02x}" for b in der[j:j + 12]) for j in range(0, len(der), 12)]
        out += [f"// key {kid}", f"static const uint8_t OTA_KEY_{i}[] = {{"] + [",\n".join("    " + r for r in rows)] + ["};"]
    out.append(f"#define OTA_KEY_COUNT {len(keys)}")
    if keys:
        out.append("static const OtaKey OTA_KEYS[] = {" + ", ".join(f"{{OTA_KEY_{i}, sizeof(OTA_KEY_{i})}}" for i in range(len(keys))) + "};")
    else:
        out.append("static const OtaKey* const OTA_KEYS = nullptr;   // no key: every update is refused")
    return "\n".join(out) + "\n", [k for k, _ in keys]


text, ids = render()
if "--check" in sys.argv[1:]:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("src/ota_keys.h is stale: run python3 firmware/common/ota_verify/tools/ota_keys.py")
    print(f"OK  ota_keys.h: {len(ids)} key(s) {' '.join(ids)}")
else:
    OUT.write_text(text)
    print(f"wrote src/ota_keys.h: {len(ids)} key(s) {' '.join(ids)}")
