#!/usr/bin/env python3
"""Make a small TEST library for the face engine: generated assets only, nothing anyone authored.

    uv run --with pillow python3 software/face-web/make_test_library.py

Writes software/face-web/library/ (git-ignored): an image skin (a gear, transparent PNG), a video
skin (a pulsing orb, WebM VP9 with an alpha channel), and the index in the library's schema
(notes/design/choreo-screen-track.md), as index.yaml and, for the page, index.json. The real library
lives on the robot (tablet plan 4.4); this exists so the skin types can be built and measured.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import shutil
import subprocess
import tempfile

from PIL import Image, ImageDraw, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(HERE, "library")


def ffmpeg():
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        return shutil.which("ffmpeg") or "ffmpeg"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def gear(path, size=512, teeth=12):
    """A gear with a hole: an object to spin in place of an eye."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c, r_out, r_in = size / 2, size * 0.47, size * 0.38
    pts = []
    for k in range(teeth * 4):
        a = 2 * math.pi * k / (teeth * 4)
        r = r_out if (k % 4) in (1, 2) else r_in
        pts.append((c + r * math.cos(a), c + r * math.sin(a)))
    d.polygon(pts, fill=(222, 184, 92, 255))
    d.ellipse([c - size * 0.30, c - size * 0.30, c + size * 0.30, c + size * 0.30], fill=(196, 150, 60, 255))
    d.ellipse([c - size * 0.12, c - size * 0.12, c + size * 0.12, c + size * 0.12], fill=(0, 0, 0, 0))
    for k in range(6):                                      # spokes, so the spin is visible
        a = 2 * math.pi * k / 6
        d.line([(c + size * 0.13 * math.cos(a), c + size * 0.13 * math.sin(a)),
                (c + size * 0.29 * math.cos(a), c + size * 0.29 * math.sin(a))], fill=(150, 110, 40, 255), width=10)
    img.save(path)


def orb_frames(folder, size=400, n=60):
    """A glowing orb whose rings pulse: a loop, transparent around it."""
    for i in range(n):
        t = i / n
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        c = size / 2
        for k in range(4):
            phase = (t + k / 4) % 1
            r = size * (0.12 + 0.34 * phase)
            a = int(255 * (1 - phase) ** 1.5)
            d.ellipse([c - r, c - r, c + r, c + r], outline=(80, 220, 255, a), width=10)
        core = size * (0.13 + 0.02 * math.sin(2 * math.pi * t))
        d.ellipse([c - core, c - core, c + core, c + core], fill=(220, 250, 255, 255))
        img = img.filter(ImageFilter.GaussianBlur(1.2))
        img.save(os.path.join(folder, f"f{i:03d}.png"))


def main():
    os.makedirs(os.path.join(LIB, "skins"), exist_ok=True)
    gear_png = os.path.join(LIB, "skins", "test-gear.png")
    gear(gear_png)

    orb_webm = os.path.join(LIB, "skins", "test-orb.webm")
    with tempfile.TemporaryDirectory() as tmp:
        orb_frames(tmp)
        # THE EXPORT SETTINGS for a video skin with transparency: VP9 in WebM, pixel format
        # yuva420p (the 'a' is the alpha plane), a loop of whole seconds, sized to the eye.
        subprocess.run([ffmpeg(), "-hide_banner", "-loglevel", "error", "-y", "-framerate", "30",
                        "-i", os.path.join(tmp, "f%03d.png"), "-c:v", "libvpx-vp9", "-pix_fmt", "yuva420p",
                        "-b:v", "1M", "-row-mt", "1", "-auto-alt-ref", "0", orb_webm], check=True)

    src = "generated by software/face-web/make_test_library.py"
    index = [
        {"id": "test-gear", "kind": "skin", "type": "image", "file": "skins/test-gear.png", "sha256": sha256(gear_png),
         "width": 512, "height": 512,
         "params": {"size": 0.80, "spin_dps": 45, "follow_look": True, "look": 0.30, "blink": "squash", "mirror": True},
         "inputs": ["lookX", "lookY", "lid"], "source": src, "licence": "test asset"},
        {"id": "test-orb", "kind": "skin", "type": "video", "file": "skins/test-orb.webm", "sha256": sha256(orb_webm),
         "width": 400, "height": 400, "fps": 30, "duration_s": 2.0,
         "params": {"size": 0.80, "spin_dps": 0, "follow_look": True, "look": 0.30, "blink": "squash", "mirror": False},
         "inputs": ["lookX", "lookY", "lid"], "source": src, "licence": "test asset"},
    ]
    with open(os.path.join(LIB, "index.json"), "w") as f:
        json.dump(index, f, indent=1)
    with open(os.path.join(LIB, "index.yaml"), "w") as f:      # the schema's own form, for reading
        for e in index:
            f.write(f"- id: {e['id']}\n")
            for k, v in e.items():
                if k != "id":
                    f.write(f"  {k}: {json.dumps(v)}\n")
    for e in index:
        print(f"{e['id']:<10} {e['type']:<6} {os.path.getsize(os.path.join(LIB, e['file'])):>8} bytes  {e['sha256'][:12]}")


if __name__ == "__main__":
    main()
