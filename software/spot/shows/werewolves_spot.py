#!/usr/bin/env python3
"""Werewolves for Spot alone, feet planted: ENCORE's Werewolves demo with OpenDubs and every stepping
move taken out, for a run on the real Spot with the song played in sync by ENCORE. Writes the ENCORE
project (open it in ENCORE to see, edit and run it) and the Spot plan the player plays.

    uv run --project <encore checkout> python software/spot/shows/werewolves_spot.py [--source DIR] [--project DIR] [--plans DIR]

From the demo (encore-m16/demo/werewolves) it drops:
  - OpenDubs: its robot, places and tracks. This show is Spot's part only.
  - spot.march, spot.turn and spot.sniff: they step Spot (BASE), which the player doesn't play yet. The
    sniff also puts the head down near the floor.
  - Spot's BODY hand track: the demo's deliberate too-fast yaw, there to show the validator.
Everything else stays as the demo has it: the howls on the held notes, the wags, head bobs, tilt,
play bow, the reacting rules and the wag policy (both baked into keyframes by ENCORE), unstow, settle.
KNOBS and REACT below change a clip's knobs (and the reacting rules' moves), within their safe ranges, where the player's first-run envelope
needs it. The song stays the user's own file: the project points at it, and nothing copies it.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

import yaml

DROP_SNIPPETS = {"spot.march", "spot.turn", "spot.sniff"}
# Where the player's first-run envelope (45 deg/s body turns, 0.15 m/s height) needs a smaller move, at
# 100 %, inside each knob's safe range:
KNOBS = {"play_bow_59": {"depth": 0.8},          # place id -> knobs; the demo's 0.9 pitched back at 45.1 deg/s
         "head_bob_7": {"amplitude": 0.7},       # the default 0.75 dipped the body at 0.153 m/s
         "wag_56": {"amplitude": 0.5},           # the demo's 0.7 yawed 49 deg/s (0.6 still 46.6)
         "wag_63": {"amplitude": 0.5}}           # the demo's 0.7 yawed 50.2 deg/s
REACT = {"spot.wag": {"amplitude": 0.5}}         # the reacting rules' wag (the demo's 0.6 yawed 46.8 deg/s)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--source", default="~/Documents/dev/encore-m16/demo/werewolves")
    ap.add_argument("--project", default="~/Documents/ENCORE/Werewolves_Spot")
    ap.add_argument("--plans", default="~/.opendubs-spot/plans")
    a = ap.parse_args()

    from encore.core.project import open_project
    from encore.robots import spot_driver

    src, root = Path(a.source).expanduser(), Path(a.project).expanduser()
    if not (src / "encore.yaml").is_file():
        sys.exit(f"refused: {src} isn't an ENCORE project")
    if root.exists():
        if not (root / "encore.yaml").is_file():
            sys.exit(f"refused: {root} exists and isn't an ENCORE project; not replacing it")
        shutil.rmtree(root)
    shutil.copytree(src, root, ignore=shutil.ignore_patterns("*.mp3", "*.wav", "*.m4a", "__pycache__"))
    react = root / "snippets" / "spot.react.snippet.yaml"
    doc = yaml.safe_load(react.read_text())
    b = doc["behaviour"]
    for rule in b.get("rules", []) + b.get("otherwise", []):
        if rule.get("play") in REACT:
            rule["params"] = {**rule.get("params", {}), **REACT[rule["play"]]}
    react.write_text(yaml.safe_dump(doc, sort_keys=False, default_flow_style=None, width=120))
    proj = yaml.safe_load((root / "encore.yaml").read_text())
    proj["name"] = "Werewolves - Spot only, feet planted"
    (root / "encore.yaml").write_text(yaml.safe_dump(proj, sort_keys=False))

    show_path = root / proj["show"]
    show = yaml.safe_load(show_path.read_text())
    show["id"] = "werewolves_spot"
    show["name"] = "Werewolves - Spot only, feet planted"
    show["robots"] = {"spot": show["robots"]["spot"]}
    show["tracks"] = [t for t in show.get("tracks", []) if t["robot"] == "spot" and t["part"] != "BODY"]
    kept, dropped = [], []
    for pl in show["places"]:
        if pl.get("robot") != "spot":
            continue
        if pl["snippet"] in DROP_SNIPPETS:
            dropped.append(f"{pl['id']} ({pl['snippet']})")
            continue
        if pl["id"] in KNOBS:
            pl["params"] = {**pl.get("params", {}), **KNOBS[pl["id"]]}
        kept.append(pl)
    show["places"] = kept
    show_path.write_text("# GENERATED by opendubs software/spot/shows/werewolves_spot.py from ENCORE's Werewolves demo.\n"
                         + yaml.safe_dump(show, sort_keys=False, default_flow_style=None, width=120))
    print(f"kept {len(kept)} Spot places; dropped {', '.join(dropped) or 'none'}")

    p = open_project(root)
    p.load_analysis()
    problems = p.problems()
    for q in problems:
        print(f"{q['severity']}: t={q.get('t', 0):.2f} s {q['msg']}")
    res = p.resolved()
    plan = spot_driver.plan(res.robots["spot"], res.clock)
    if "BASE" in {c["part"] for c in plan["commands"]}:
        sys.exit("refused: the plan moves BASE; this show keeps its feet planted")
    if any(q["severity"] == "error" for q in problems) or plan["problems"]:
        for q in plan["problems"]:
            print(f"plan problem: {q}")
        sys.exit("not written: the show has errors or plan problems, see above")
    out = Path(a.plans).expanduser() / "werewolves_spot.spot-plan.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(plan, indent=1))
    parts = sorted({c["part"] for c in plan["commands"]})
    print(f"{root}\n{out}: {plan['windows']} windows, {len(plan['commands'])} commands ({', '.join(parts)})")


if __name__ == "__main__":
    main()
