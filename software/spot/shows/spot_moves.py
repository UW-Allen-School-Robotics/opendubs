#!/usr/bin/env python3
"""Spot's first moves show: a short, Spot-only ENCORE show for a first run on the real robot, in an open
space with the Mac on an Ethernet cable. Writes the ENCORE project (open it in ENCORE to see and edit it)
and the Spot plan the player plays.

    uv run --project <encore checkout> python software/spot/shows/spot_moves.py [--project DIR] [--plans DIR]

Feet planted the whole time: no BASE part (no stepping, no turning), so the cable is never pulled. The
size knobs sit low in their ranges, and there is no music: the beat is a fixed 100 bpm grid, about 45 s.
No sniff: its head goes down to just above the floor.

Bars (4 beats each):
  1-2   wake up: the arm unfolds from stowed to the head pose
  3-4   head tilt: the curious dog, one side then the other
  5-6   tail wag
  7-8   howl, four beats long: sits back, head to the sky, jaw open
  9-10  head bob
  11-12 point left: the head turns 60 deg to Spot's own left (shoulder sh0 +60), holds, comes back.
        The one strongly handed move, so a glance shows whether the arm's signs match the preview.
  13-14 play bow, shallow
  15-16 howl again
  17-18 settle: body down a little, arm stowed
"""
import argparse
import json
import sys
from pathlib import Path

import yaml

BPM = 100

# (snippet, anchor beat, knobs). Each anchor is where the snippet's own anchor beat lands (see list_snippets).
# A beat apart: a snippet's first key on the previous one's last replaces it, and then that move takes one beat.
PLACES = [
    ("spot.unstow", 9, {}),                                   # its anchor is its end: head up on beat 9
    ("spot.head_tilt", 11, {"amplitude": 0.6, "side": "left"}),
    ("spot.wag", 19, {"amplitude": 0.5}),
    ("spot.howl", 29, {"note_beats": 4, "jaw": 0.8}),
    ("spot.head_bob", 35, {"amplitude": 0.5}),
    ("spot.play_bow", 55, {"depth": 0.5}),
    ("spot.howl", 62, {"note_beats": 4, "jaw": 0.8}),
    ("spot.settle", 70, {"low": 0.06}),
]

# Point left, hand-placed in the gap after the head bob: the head pose with the shoulder turned. sh0 is
# positive to Spot's own left (counter-clockwise seen from above). 60 deg in 2 beats is 50 deg/s.
HEAD = {"sh0": 0, "sh1": -90.3, "el0": 128.7, "el1": 0, "wr0": -28.4, "wr1": 0}     # ENCORE's "head" pose
POINT_LEFT = [{"beat": 44, **HEAD}, {"beat": 46, **HEAD, "sh0": 60}, {"beat": 49, **HEAD, "sh0": 60},
              {"beat": 51, **HEAD}]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--project", default="~/Documents/ENCORE/Spot_Moves")
    ap.add_argument("--plans", default="~/.opendubs-spot/plans")
    a = ap.parse_args()

    from encore.core.project import open_project
    from encore.robots import spot_driver

    root = Path(a.project).expanduser()
    (root / "shows").mkdir(parents=True, exist_ok=True)
    (root / "encore.yaml").write_text(yaml.safe_dump(
        {"format": "encore.project/1", "name": "Spot moves", "songs": {}, "show": "shows/spot_moves.yaml",
         "stage": {"width_m": 6, "depth_m": 5}}, sort_keys=False))
    places = [{"id": f"{s.split('.')[-1]}_{i + 1}", "snippet": s, "robot": "spot", "beat": b,
               **({"params": k} if k else {})} for i, (s, b, k) in enumerate(PLACES)]
    show = {"format": "encore.show/1", "id": "spot_moves", "name": "Spot moves (first run, feet planted)",
            "music": {"bpm": BPM, "beats_per_bar": 4, "grid": "fixed"},
            "robots": {"spot": {"profile": "spot", "at": [0, 0], "facing_deg": 0}},
            "tracks": [{"robot": "spot", "part": "ARM", "keys": POINT_LEFT}], "places": places, "markers": []}
    (root / "shows" / "spot_moves.yaml").write_text(
        "# GENERATED by opendubs software/spot/shows/spot_moves.py. Edit it in ENCORE, or there and run it again.\n"
        + yaml.safe_dump(show, sort_keys=False, default_flow_style=None, width=120))

    p = open_project(root)
    problems = p.problems()
    for q in problems:
        print(f"{q['severity']}: t={q.get('t', 0):.2f} s {q['msg']}")
    res = p.resolved()
    plan = spot_driver.plan(res.robots["spot"], res.clock)
    if "BASE" in {c["part"] for c in plan["commands"]}:
        sys.exit("refused: the show moves BASE; this one keeps its feet planted")
    if any(q["severity"] == "error" for q in problems) or plan["problems"]:
        sys.exit(f"not written: {len(plan['problems'])} plan problems, see above")
    out = Path(a.plans).expanduser() / "spot-moves.spot-plan.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(plan, indent=1))
    parts = sorted({c["part"] for c in plan["commands"]})
    print(f"{root}: {len(places)} placements at {BPM} bpm\n{out}: {plan['windows']} windows, "
          f"{len(plan['commands'])} commands ({', '.join(parts)})")


if __name__ == "__main__":
    main()
